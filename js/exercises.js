/* 영상이 필요하면 검색으로 보낸다. 앱 안에 영상을 품지 않는다 —
 * 오프라인에서 못 쓰고, 링크가 죽으면 안내가 통째로 거짓이 된다. */
export function videoSearchUrl(id) {
  const ex = EXERCISES[id];
  if (!ex) return null;
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(ex.search)}`;
}
